const JS: &str = r"
const rowsEl = document.getElementById('rows');
const template = document.getElementById('row-template');
const statsEl = document.getElementById('stats');
const countEl = document.getElementById('count');
const searchEl = document.getElementById('search');
const areaEl = document.getElementById('area');
const statusEl = document.getElementById('status');
const milestoneEl = document.getElementById('milestone');
const aspectEl = document.getElementById('aspect');

function renderStats() {
  const counts = { works: 0, partial: 0, unverified: 0, broken: 0 };
  let withAspect = 0;
  for (const c of CAPABILITIES) {
    counts[c.status] = (counts[c.status] || 0) + 1;
    if (c.unverified_aspect) withAspect += 1;
  }
  statsEl.innerHTML = '';
  for (const key of ['works', 'partial', 'unverified', 'broken']) {
    const div = document.createElement('div');
    div.className = 'stat';
    div.textContent = key + ': ' + counts[key] + ' / ' + CAPABILITIES.length;
    statsEl.appendChild(div);
  }
  const aspectDiv = document.createElement('div');
  aspectDiv.className = 'stat';
  aspectDiv.textContent = 'carry unverified aspect: ' + withAspect + ' / ' + CAPABILITIES.length;
  statsEl.appendChild(aspectDiv);
}

function renderRows() {
  const q = searchEl.value.trim().toLowerCase();
  const area = areaEl.value;
  const status = statusEl.value;
  const milestone = milestoneEl.value;
  const aspectOnly = aspectEl.checked;

  rowsEl.innerHTML = '';
  let shown = 0;
  for (const cap of CAPABILITIES) {
    if (area && cap.area !== area) continue;
    if (status && cap.status !== status) continue;
    if (milestone && cap.milestone !== milestone) continue;
    if (aspectOnly && !cap.unverified_aspect) continue;
    if (q) {
      const hay = (cap.id + ' ' + cap.title + ' ' + cap.status_prose + ' ' +
        cap.decided_in + ' ' + cap.unverified_aspect + ' ' + cap.tests.join(' ')).toLowerCase();
      if (!hay.includes(q)) continue;
    }
    shown += 1;
    const node = template.content.cloneNode(true);
    node.querySelector('.id').textContent = cap.id;
    const statusSpan = node.querySelector('.status');
    statusSpan.textContent = cap.status;
    statusSpan.classList.add(cap.status);
    node.querySelector('.title').textContent = cap.title;
    node.querySelector('.area-badge').textContent = cap.area + ' · ' + cap.milestone;
    node.querySelector('.status-prose').textContent = 'Status: ' + cap.status_prose;
    const aspectP = node.querySelector('.unverified-aspect');
    if (cap.unverified_aspect) {
      aspectP.textContent = 'Unverified aspect: ' + cap.unverified_aspect;
    } else {
      aspectP.remove();
    }
    node.querySelector('.tests').textContent =
      cap.tests.length ? 'Proven by: ' + cap.tests.join('\n') : 'Proven by: (none cited)';
    node.querySelector('.captures').textContent =
      cap.captures.length ? 'Looks like: ' + cap.captures.join(', ') : '';
    node.querySelector('.decided').textContent = cap.decided_in ? 'Decided in: ' + cap.decided_in : '';
    node.querySelector('.source').textContent = cap.source_file + ':' + cap.source_line;
    node.querySelector('.how').remove();
    node.querySelector('.behaviour').remove();
    rowsEl.appendChild(node);
  }
  countEl.textContent = shown + ' / ' + CAPABILITIES.length + ' shown';
}

for (const el of [searchEl, areaEl, statusEl, milestoneEl, aspectEl]) {
  el.addEventListener('input', renderRows);
}
renderStats();
renderRows();
";

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::Status;
    use std::path::PathBuf;

    #[test]
    fn embeds_valid_looking_data_and_has_no_external_refs() {
        let cap = Capability {
            id: "M1-01".to_owned(),
            title: "Has a \"quote\" and <tag>".to_owned(),
            area: "graph".to_owned(),
            milestone: "m1-the-graph".to_owned(),
            status: Status::Works,
            unverified_aspect: None,
            status_prose: "works.".to_owned(),
            tests: vec!["mergewright::tests::it::sample".to_owned()],
            captures: vec!["docs/shots/x.txt".to_owned()],
            decided_in: "ADR-0001".to_owned(),
            decisions: Vec::new(),
            source_file: PathBuf::from("docs/capabilities/m1-the-graph.md"),
            source_line: 27,
        };
        let html = render(&[cap]);
        assert!(html.contains("M1-01"));
        assert!(
            !html.contains("</script>\n{data"),
            "sanity: template rendered"
        );
        assert!(!html.contains("http://"));
        assert!(!html.contains("https://"));
        assert!(!html.contains("cdn."));
        // The literal `</script>` from the title must never appear raw.
        assert!(!html.contains("<tag></script>"));
    }
}
